"""Paired end-to-end report for the RAG comparison (reads run directories; runs no model).

    python -m rag_opt.e2e_report --root rag_opt/results/e2e            # dirs named <model>__<arm>
    python -m rag_opt.e2e_report --run "base/none=rag/integration/results/qwen3-4b-q4-none-val-rerun" \
        --run "base/bm25=rag/integration/results/qwen3-4b-q4-bm25-val-rerun" --out /tmp/x   # ad-hoc

Per model: every arm vs `none`, and `gated` vs `bm25`. Same requirement keys only (intersection). Metrics come from
the frozen benchmark/metrics.py; paired statistics from rag/significance.py (exact McNemar on per-requirement
correctness, paired bootstrap 95% CI of the macro-F1 difference, 2,000 resamples, seed 0). Each run is labelled
with its backend and its provenance label (MOCK runs stay labelled MOCK).
"""
import argparse
import json
import statistics
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from benchmark import metrics as M  # noqa: E402
from rag.significance import mcnemar_exact, paired_bootstrap_diff  # noqa: E402
from rag_opt.error_analysis import echo  # noqa: E402

TAGS = ("equivalent_skill_alias", "rag_suggests_absent_skill", "certification", "missing_evidence", "negation_trap")
ORDER = ("none", "bm25", "gated", "gated-qdrant")


def load(d):
    d = Path(d)
    recs = {(r["case_id"], r["req_id"]): r for r in map(json.loads, (d / "predictions.jsonl").read_text().splitlines()) if r}
    cfg = json.loads((d / "config.json").read_text()) if (d / "config.json").exists() else {}
    prov = json.loads((d / "provenance.json").read_text()) if (d / "provenance.json").exists() else {}
    return recs, cfg, prov


def summary(recs, cfg, prov, keys):
    rs = [recs[k] for k in keys]
    m = M.compute(rs)
    lat = sorted(r["latency_s"] for r in rs)
    pt = [r.get("call", {}).get("prompt_tokens") for r in rs if r.get("call", {}).get("prompt_tokens")]
    b = cfg.get("backend", {})
    return {"backend": f"{b.get('model_id') or b.get('backend')} @ {b.get('base_url', '-')}", "revision": b.get("revision"),
            "knowledge": cfg.get("knowledge"), "label": prov.get("label") or ("LIVE (recorded)" if b.get("is_model") else "not a model"),
            "n": len(rs), "macro_f1": round(m["final"]["macro_f1"], 4), "accuracy": round(m["final"]["accuracy"], 4),
            "false_met_rate": m["final"]["false_met_rate"] and round(m["final"]["false_met_rate"], 4),
            "json_valid": round(m["json_schema_validity"], 4), "template_echo": sum(echo(r) for r in rs),
            "uncertain_rate": round(sum(r["decision"] == "UNCERTAIN" for r in rs) / len(rs), 4),
            "human_review_rate": round(m["needs_human_review_rate"], 4),
            "latency_p50_s": round(M.pct(lat, 0.5), 2), "latency_p95_s": round(M.pct(lat, 0.95), 2),
            "client_peak_rss_mb": prov.get("client_peak_rss_mb"), "server_peak_rss_mb": prov.get("server_peak_rss_mb"),
            "refs_per_req": round(statistics.fmean(len(r["rag_refs"]) for r in rs), 3),
            "prompt_tokens_mean": round(statistics.fmean(pt), 1) if pt else None,
            "tag_accuracy": {t: m["per_tag_accuracy"].get(t) for t in TAGS}}


def compare(base, cand, keys):
    gold = [base[k]["gold_decision"] for k in keys]
    bd, cd = [base[k]["decision"] for k in keys], [cand[k]["decision"] for k in keys]
    x, y, p = mcnemar_exact([a == g for a, g in zip(bd, gold)], [a == g for a, g in zip(cd, gold)])
    d, (lo, hi) = paired_bootstrap_diff(gold, bd, cd)
    return {"n": len(keys), "delta_macro_f1": round(d, 4), "ci95": [round(lo, 4), round(hi, 4)],
            "base_only_correct": x, "cand_only_correct": y, "mcnemar_p": round(p, 4)}


def report(runs):
    """runs: {model: {arm: dir}}"""
    out = {}
    for model, arms in runs.items():
        loaded = {arm: load(d) for arm, d in arms.items()}
        keys = sorted(set.intersection(*[set(r) for r, _, _ in loaded.values()]))
        block = {"dirs": {a: str(d) for a, d in arms.items()},
                 "runs": {a: summary(r, c, p, keys) for a, (r, c, p) in sorted(loaded.items(), key=lambda x: ORDER.index(x[0]) if x[0] in ORDER else 9)},
                 "paired": {}}
        pairs = [(a, "none") for a in loaded if a != "none" and "none" in loaded]
        if "gated" in loaded and "bm25" in loaded:
            pairs.append(("gated", "bm25"))
        for cand, base in pairs:
            block["paired"][f"{cand} vs {base}"] = compare(loaded[base][0], loaded[cand][0], keys)
        out[model] = block
    return out


def to_markdown(out):
    L = ["# End-to-end RAG comparison (generated by `python -m rag_opt.e2e_report`)", ""]
    cols = ["label", "backend", "knowledge", "n", "macro_f1", "false_met_rate", "json_valid", "template_echo", "uncertain_rate",
            "latency_p50_s", "latency_p95_s", "client_peak_rss_mb", "server_peak_rss_mb", "refs_per_req", "prompt_tokens_mean"]
    for model, block in out.items():
        L += [f"## Matcher: {model}", "", "| arm | " + " | ".join(cols) + " |", "|---" * (len(cols) + 1) + "|"]
        L += [f"| {a} | " + " | ".join(str(s.get(c)) for c in cols) + " |" for a, s in block["runs"].items()]
        L += ["", "| arm | " + " | ".join(TAGS) + " |", "|---" * (len(TAGS) + 1) + "|"]
        L += [f"| {a} | " + " | ".join(f"{v['accuracy']:.2f} (n={v['n']})" if v else "n/a" for v in s["tag_accuracy"].values()) + " |"
              for a, s in block["runs"].items()]
        L += ["", "| comparison | Δ macro-F1 | 95% CI | base-only / cand-only correct | McNemar p |", "|---|---|---|---|---|"]
        L += [f"| {k} | {v['delta_macro_f1']:+.3f} | [{v['ci95'][0]:+.3f}, {v['ci95'][1]:+.3f}] | {v['base_only_correct']} / "
              f"{v['cand_only_correct']} | {v['mcnemar_p']} |" for k, v in block["paired"].items()]
        L += ["", "Run directories: " + ", ".join(f"{a}: `{d}`" for a, d in block["dirs"].items()), ""]
    return "\n".join(L)


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--root", help="directory holding <model>__<arm> run directories")
    ap.add_argument("--run", action="append", default=[], help="MODEL/ARM=DIR (repeatable)")
    ap.add_argument("--out", help="output stem (default <root>/e2e_report)")
    a = ap.parse_args(argv)
    runs = defaultdict(dict)
    if a.root:
        for d in sorted(Path(a.root).iterdir()):
            if (d / "predictions.jsonl").exists() and "__" in d.name:
                model, arm = d.name.split("__", 1)
                runs[model][arm] = d
    for spec in a.run:
        name, d = spec.split("=", 1)
        model, arm = name.split("/", 1)
        runs[model][arm] = Path(d)
    if not runs:
        ap.error("no runs found")
    out = report(runs)
    stem = Path(a.out or Path(a.root) / "e2e_report")
    stem.parent.mkdir(parents=True, exist_ok=True)
    Path(f"{stem}.json").write_text(json.dumps(out, indent=1, default=str) + "\n")
    Path(f"{stem}.md").write_text(to_markdown(out))
    print(to_markdown(out))
    return out


if __name__ == "__main__":
    main()
