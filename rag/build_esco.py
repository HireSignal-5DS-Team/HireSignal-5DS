"""Build the ESCO ICT/data skill subset used as the terminology knowledge base.

Source: ESCO classification (European Commission, CC BY 4.0), obtained from the
Tabiya CSV mirror on GitHub because the official ESCO portal is not reachable from
our build environment. The mirror commit and file hashes are pinned below so the
subset is reproducible bit-for-bit.

Usage: python rag/build_esco.py
"""
import hashlib
import json
import re
import subprocess
from pathlib import Path

import pandas as pd

HERE = Path(__file__).parent
SRC = HERE / "data/esco/_src"  # gitignored download cache
OUT = HERE / "data/esco/esco_ict_skills.jsonl"
MIRROR = "https://github.com/tabiya-tech/taxonomy-model-application"
COMMIT = "eb3e5f445f6c0271641851dd2d27621d812c4662"
FOLDER = "data-sets/csv/esco-v1.1.2"  # folder name says v1.1.2, its model_info.csv says "ESCO v1.1.1"
SHA256 = {
    "skills.csv": "9717a4521c94cc0eeefe519b2fccddac0a406a729d519bf3357e8ed60723fee2",
    "occupations.csv": "99ebee8b5d1ee376d00b0633b4e941167e37dcf0247ec7e8d4533a7a44dd7cfc",
    "occupation_to_skill_relations.csv": "28e4565583797edee7c3f20b743548cfefc9483683d549724ca69b2c9a9eb6d5",
}
# ISCO groups covering HireSignal's target roles: 25 ICT professionals (incl. data scientist 2511.4,
# data analyst 2511.3), 35 ICT technicians, 212 mathematicians/statisticians, 1330 ICT managers.
ISCO_PREFIX = r"^(25|35|212|1330)"


def fetch():
    repo = SRC / "mirror"
    if not repo.exists():
        subprocess.run(["git", "clone", "-q", "--filter=blob:none", "--no-checkout", MIRROR, str(repo)], check=True)
    subprocess.run(["git", "-C", str(repo), "checkout", "-q", COMMIT, "--", *[f"{FOLDER}/{f}" for f in SHA256]], check=True)
    for f, h in SHA256.items():
        got = hashlib.sha256((repo / FOLDER / f).read_bytes()).hexdigest()
        if got != h:
            raise SystemExit(f"hash mismatch for {f}: {got}")
    return repo / FOLDER


def build():
    d = fetch()
    occ = pd.read_csv(d / "occupations.csv", dtype=str, keep_default_na=False)
    rel = pd.read_csv(d / "occupation_to_skill_relations.csv", dtype=str, keep_default_na=False)
    sk = pd.read_csv(d / "skills.csv", dtype=str, keep_default_na=False)
    target = occ[occ.CODE.str.match(ISCO_PREFIX)]
    linked = set(rel[rel.OCCUPATIONID.isin(target.ID)].SKILLID)
    # transversal skills (teamwork, communication...) appear in most job ads but are linked to few occupations
    keep = sk[sk.ID.isin(linked) | (sk.REUSELEVEL == "transversal")]
    with OUT.open("w", encoding="utf-8") as f:
        for r in keep.sort_values("ORIGINURI").itertuples():
            alts = [a for a in r.ALTLABELS.split("\n") if a and a != r.PREFERREDLABEL]
            text = r.PREFERREDLABEL + (". Also known as: " + "; ".join(alts) if alts else "") + ". " + r.DESCRIPTION
            f.write(json.dumps({
                "doc_id": r.ORIGINURI, "source_type": "esco", "title": r.PREFERREDLABEL,
                "skill_type": r.SKILLTYPE, "reuse_level": r.REUSELEVEL, "url": r.ORIGINURI,
                "text": text.strip(),
            }, ensure_ascii=False) + "\n")
    print(f"occupations={len(target)} skills_total={len(sk)} subset={len(keep)} -> {OUT}")
    return sk, keep


# Terms frequent in data/tech job ads, fixed before measuring (not tuned to ESCO).
PROBE_TERMS = ["Python", "R", "SQL", "NoSQL", "Java", "JavaScript", "Scala", "machine learning", "deep learning",
               "statistics", "data mining", "data visualisation", "big data", "Hadoop", "Spark", "TensorFlow",
               "PyTorch", "scikit-learn", "pandas", "Docker", "Kubernetes", "Git", "Linux", "cloud computing",
               "AWS", "Azure", "Power BI", "Tableau", "Excel", "Agile", "Scrum", "ETL", "data warehouse",
               "natural language processing", "computer vision", "teamwork", "communication", "English"]


def coverage(sk, keep):
    def hit(df, term):
        rx = re.compile(rf"(?<![\w+#]){re.escape(term)}(?![\w+#])", re.I)
        labels = df.PREFERREDLABEL + "\n" + df.ALTLABELS
        m = df[labels.map(lambda s: bool(rx.search(s)))]
        return m.PREFERREDLABEL.head(2).tolist()
    rows = ["| Term | In full ESCO (example labels) | In HireSignal subset |", "|---|---|---|"]
    n_full = n_sub = 0
    for t in PROBE_TERMS:
        full, sub = hit(sk, t), hit(keep, t)
        n_full += bool(full); n_sub += bool(sub)
        rows.append(f"| {t} | {'; '.join(full) or 'no'} | {'yes' if sub else 'no'} |")
    head = f"Probe terms: {len(PROBE_TERMS)}. Found in full ESCO: {n_full}. Found in subset: {n_sub}.\n\n"
    (HERE / "docs/esco_coverage.md").write_text("# ESCO coverage check (generated by build_esco.py)\n\n" + head + "\n".join(rows) + "\n")
    print(head.strip())


if __name__ == "__main__":
    coverage(*build())
