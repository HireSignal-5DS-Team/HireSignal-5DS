"""Original vs reviewed benchmark, per source type, on the same configurations.

Usage: python rag/compare_results.py [reviewed_results_dir]   (default eval/results_queries_reviewed)
Reads eval/results/results.csv and <dir>/results.csv; prints and writes <dir>/comparison.md.
"""
import sys
from pathlib import Path

import numpy as np
import pandas as pd

HERE = Path(__file__).parent
KEYS = ["type", "strategy", "model", "mode", "setting"]


def metrics(df):
    def agg(g):
        r = g.first_hit_rank
        return pd.Series({"n": len(g), "hit@1": int((r == 1).sum()), "hit@5": int((r <= 5).sum()),
                          "MRR@10": round((1 / r).fillna(0).mean(), 3),
                          "nDCG@10": round((1 / np.log2(r + 1)).fillna(0).mean(), 3)})
    return df[df.type != "none"].groupby(KEYS).apply(agg, include_groups=False)


def main(reviewed_dir):
    orig = pd.read_csv(HERE / "eval/results/results.csv")
    rev = pd.read_csv(reviewed_dir / "results.csv")
    table = metrics(orig).join(metrics(rev), lsuffix=" orig", rsuffix=" reviewed").reset_index()
    md = ("# Original vs reviewed labels (generated by compare_results.py)\n\n"
          "Original: AI-drafted gold, all queries. Reviewed: user-approved AI-assisted adjudication; "
          "rejected queries removed from the denominator.\n\n" + table.to_markdown(index=False) + "\n")
    (reviewed_dir / "comparison.md").write_text(md, encoding="utf-8")
    print(md)


if __name__ == "__main__":
    main(Path(sys.argv[1]) if len(sys.argv) > 1 else HERE / "eval/results_queries_reviewed")
