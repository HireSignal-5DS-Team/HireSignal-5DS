"""Verify that the retrieval index the API serves contains the whole knowledge base.

Builds the API configuration (structure chunking, e5-small, Qdrant index in rag/index/), then checks IDs, counts,
provenance, character coverage of job chunks, index contents and one retrieval per source.
Writes docs/INDEX_VERIFICATION.md. Exits non-zero if any check fails.

Usage: HF_HOME=<cache> CUDA_VISIBLE_DEVICES= python rag/verify_index.py   (stop the API first: it locks rag/index)
"""
import re
from collections import Counter
from pathlib import Path

from corpus import build_chunks, load_esco, load_jobs
from retrieval import Retriever

HERE = Path(__file__).parent
STRATEGY, MODEL = "structure", "e5-small"  # the API defaults
checks, rows = [], []


def check(name, ok, detail=""):
    checks.append((name, bool(ok), detail))


jobs, esco = load_jobs(), load_esco()
check("20 job postings loaded", len(jobs) == 20, f"{len(jobs)}")
check("1,621 ESCO concepts loaded", len(esco) == 1621, f"{len(esco)}")
check("job IDs unique", len({j['doc_id'] for j in jobs}) == len(jobs))
check("ESCO URIs unique", len({e['doc_id'] for e in esco}) == len(esco))
check("job source URLs are usajobs.gov/job/<id>",
      all(j["source_url"] == f"https://www.usajobs.gov/job/{j['doc_id'].removeprefix('usajobs-')}" for j in jobs))
check("job rights recorded", all("public domain" in j["rights"] for j in jobs))
check("ESCO URLs are data.europa.eu/esco/skill/<uuid>",
      all(re.fullmatch(r"http://data\.europa\.eu/esco/skill/[0-9a-f-]{36}", e["url"]) for e in esco))

chunks = build_chunks(STRATEGY, jobs, esco)
job_chunks = [c for c in chunks if c["source_type"] == "job"]
per_job = Counter(c["doc_id"] for c in job_chunks)
check("every posting has chunks", set(per_job) == {j["doc_id"] for j in jobs})
check("one chunk per ESCO concept", sum(c["source_type"] == "esco" for c in chunks) == len(esco))
check("chunk IDs unique", len({c['chunk_id'] for c in chunks}) == len(chunks))
uncovered = 0
for j in jobs:
    covered = [False] * len(j["text"])
    for c in (c for c in job_chunks if c["doc_id"] == j["doc_id"]):
        covered[c["start"]:c["end"]] = [True] * (c["end"] - c["start"])
    uncovered += sum(1 for ch, cov in zip(j["text"], covered) if not cov and not ch.isspace())
check("every non-space character of every posting is in a chunk", uncovered == 0, f"{uncovered} uncovered")

r = Retriever(chunks, model=MODEL, store_path=HERE / "index")
n_points = r.qdrant.count(r.collection).count
check("dense index holds every chunk", n_points == len(chunks), f"{n_points} points / {len(chunks)} chunks")
check("BM25 index holds every chunk", r.bm25.scores["num_docs"] == len(chunks), f"{r.bm25.scores['num_docs']} documents")
stored = {p.payload["doc_id"] for p in r.qdrant.scroll(r.collection, limit=len(chunks) + 10, with_payload=True)[0]}
check("index payload covers all 1,641 source documents", stored == {j["doc_id"] for j in jobs} | {e["doc_id"] for e in esco},
      f"{len(stored)} documents")
job_hit = r.search("must be a U.S. Citizen", k=1, mode="dense", filters={"doc_id": jobs[0]["doc_id"]})["results"]
esco_hit = r.search("Python programming", k=1, mode="dense", filters={"source_type": "esco"})["results"]
check("Matcher can retrieve job evidence", job_hit and job_hit[0][0]["source_type"] == "job",
      job_hit and job_hit[0][0]["chunk_id"])
check("Matcher can retrieve ESCO evidence", esco_hit and esco_hit[0][0]["source_type"] == "esco",
      esco_hit and esco_hit[0][0]["title"])
r.qdrant.close()

lines = ["# Index verification (generated by verify_index.py)\n",
         f"Configuration: {STRATEGY} chunking, {MODEL}, Qdrant collection `{r.collection}` in `rag/index/`.\n",
         f"Chunks: {len(job_chunks)} job + {len(esco)} ESCO = {len(chunks)}.\n",
         "| Check | Result | Detail |", "|---|---|---|"]
lines += [f"| {n} | {'PASS' if ok else 'FAIL'} | {d} |" for n, ok, d in checks]
lines += ["", "## Chunks per posting", "", "| job_id | title | chunks | words |", "|---|---|---|---|"]
lines += [f"| {j['doc_id']} | {j['title']} | {per_job[j['doc_id']]} | {len(j['text'].split())} |" for j in jobs]
(HERE / "docs/INDEX_VERIFICATION.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
print("\n".join(lines[:5 + len(checks)]))
raise SystemExit(0 if all(ok for _, ok, _ in checks) else 1)
