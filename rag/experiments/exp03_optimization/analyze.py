import json
import sys
from math import comb
from pathlib import Path

import numpy as np
import pandas as pd

HERE = Path(__file__).parent
R = HERE / "results"
BASE = "structure@300 | e5-small"
BUDGET = {"realtime": 300, "async": 2000}  # p95 ms per query (PLAN.md)
RAM_BUDGET_MB = 1500
GROUPS = {"ESCO": ["esco"], "scoped": ["scoped"], "global": ["global"], "Matcher": ["esco", "scoped"]}


def m(g):
    r = g["rank"]
    return {"n": len(g), "hit@1": int((r == 1).sum()), "hit@5": int((r <= 5).sum()), "hit@10": int((r <= 10).sum()),
            "MRR": round(float((1 / r).fillna(0).mean()), 3), "nDCG@10": round(float((1 / np.log2(r + 1)).fillna(0).mean()), 3)}


def attribution(g, queries):
    """Top-1 result comes from the right source document (job posting / ESCO concept)."""
    ok = [(row.top_doc == queries[row.qid].get("job_id")) if row.type == "job" else (row.top_doc in queries[row.qid]["gold_uris"])
          for row in g.itertuples()]
    return round(float(np.mean(ok)), 3) if ok else None


def mcnemar(a, b):
    x, y = int((a & ~b).sum()), int((~a & b).sum())
    n = x + y
    return x, y, (min(1.0, 2 * sum(comb(n, k) for k in range(min(x, y) + 1)) / 2 ** n) if n else 1.0)


def boot(diff, n=2000, seed=0):
    rng = np.random.default_rng(seed)
    s = [diff[rng.integers(0, len(diff), len(diff))].mean() for _ in range(n)]
    return float(np.percentile(s, 2.5)), float(np.percentile(s, 97.5))


def paired(df, cand, settings, base=BASE):
    get = lambda c: df[(df.config == c) & df.setting.isin(settings)].set_index(["qid", "setting"])["rank"].sort_index()
    a, b = get(base), get(cand)
    rr = lambda s: (1 / s).fillna(0).to_numpy()
    d = rr(b) - rr(a)
    lo, hi = boot(d)
    x, y, p = mcnemar(a == 1, b == 1)
    return {"base-only@1": x, "cand-only@1": y, "McNemar p": round(p, 3), "MRR diff": round(float(d.mean()), 3),
            "CI lo": round(lo, 3), "CI hi": round(hi, 3)}


def dev():
    df = pd.read_csv(R / "dev_per_query.csv")
    meta = pd.read_csv(R / "dev_configs.csv").set_index("config")
    queries = {q["qid"]: q for q in map(json.loads, open(HERE.parents[1] / "eval/queries_reviewed.jsonl", encoding="utf-8"))}
    ans = df[df.type != "none"]
    rows, stats = [], []
    for cfg in df.config.unique():
        g = ans[ans.config == cfg]
        row = {"group": meta.loc[cfg, "group"], "config": cfg}
        for name, st in GROUPS.items():
            for k, v in m(g[g.setting.isin(st)]).items():
                if k != "n" or name == "Matcher":
                    row[f"{name} {k}"] = v
        row["attribution@1 global"] = attribution(g[g.setting == "global"], queries)
        row["attribution@1 ESCO"] = attribution(g[g.setting == "esco"], queries)
        row["single-shot median ms"] = round(float(g.ms.median()), 1)
        row.update(meta.loc[cfg][["job_chunks", "indexing_s", "index_mb", "embed_mem_mb", "rerank_mem_mb"]].to_dict())
        rows.append(row)
        if cfg != BASE:
            for label, st in (("Matcher", ["esco", "scoped"]), ("global", ["global"])):
                stats.append({"config": cfg, "settings": label, **paired(df, cfg, st)})
    t, s = pd.DataFrame(rows), pd.DataFrame(stats)
    t.to_csv(R / "dev_summary.csv", index=False)
    s.to_csv(R / "dev_stats.csv", index=False)
    # finalists: dev Matcher MRR >= baseline, and single-shot median not more than 3x the async budget
    base_mrr = t.loc[t.config == BASE, "Matcher MRR"].iloc[0]
    fin = t[((t["Matcher MRR"] >= base_mrr) & (t["single-shot median ms"] <= 3 * BUDGET["async"])) | (t.config == BASE)]
    finalists = [[r.group, *r.config.split(" | ")[:1], *(_split(r.config))] for r in fin.itertuples()]
    json.dump(finalists, open(HERE / "finalists.json", "w"), indent=1)
    md = ["# exp03 — development results (generated by analyze.py dev)\n",
          f"Baseline: `{BASE}` (production). Matcher = ESCO + job-filtered (job-ID filter mandatory). Global = stress test.\n"]
    for grp in t.group.unique():
        md += [f"## {grp}\n", t[t.group == grp].drop(columns="group").to_markdown(index=False), ""]
    md += ["## Paired comparisons vs baseline (bootstrap 95% CI of MRR difference; exact McNemar on Hit@1)\n",
           s.to_markdown(index=False), "", f"Finalists (Matcher MRR ≥ baseline, single-shot median ≤ {3 * BUDGET['async']} ms): "
           + ", ".join(f"`{c}`" for c in fin.config)]
    (R / "dev_summary.md").write_text("\n".join(md) + "\n")
    print(t[["config", "Matcher MRR", "global MRR", "single-shot median ms"]].to_string(index=False))


def _split(config):
    """'pc@1s | e5-small > bge@10' -> [embedding, reranker, top_n]."""
    rest = config.split(" | ")[1]
    if " > " not in rest:
        return [rest, None, None]
    emb, rr = rest.split(" > ")
    name, n = rr.rsplit("@", 1)
    return [emb, name, int(n)]


def calibration():
    """Per collection (job-scoped, ESCO), threshold on the reranker score (or cosine without reranker) maximising
    balanced accuracy; 5-fold CV estimate on the calibration split; final threshold fit on all of it."""
    df = pd.read_csv(R / "calibration_per_query.csv")
    df["answerable"] = df.type != "none"
    df["coll"] = np.where((df.type == "job") | (df.collection == "job"), "job", "esco")
    out, rows = {}, []
    for cfg, g in df.groupby("config"):
        out[cfg] = {}
        for coll, h in g.groupby("coll"):
            score = (h.top_rerank if h.top_rerank.notna().any() else h.top_dense).to_numpy()
            y = h.answerable.to_numpy()

            def fit(idx):
                cands = np.unique(score[idx])
                bal = lambda t: 0.5 * ((score[idx][y[idx]] >= t).mean() + (score[idx][~y[idx]] < t).mean())
                return max(cands, key=bal)

            rng = np.random.default_rng(0)
            folds = np.array_split(rng.permutation(len(h)), 5)
            acc = []
            for k in range(5):
                test = folds[k]
                train = np.concatenate([folds[i] for i in range(5) if i != k])
                t = fit(train)
                acc.append(((score[test] >= t) == y[test]).mean())
            t_all = float(fit(np.arange(len(h))))
            out[cfg][coll] = t_all
            rows.append({"config": cfg, "collection": coll, "n": len(h), "score": "reranker" if h.top_rerank.notna().any() else "cosine",
                         "threshold (all data)": round(t_all, 3), "5-fold CV accuracy": round(float(np.mean(acc)), 3),
                         "answerable kept (all data)": f"{int((score[y] >= t_all).sum())}/{int(y.sum())}",
                         "unsupported abstained (all data)": f"{int((score[~y] < t_all).sum())}/{int((~y).sum())}"})
    json.dump(out, open(HERE / "thresholds.json", "w"), indent=1)
    t = pd.DataFrame(rows)
    (R / "calibration_summary.md").write_text("# Abstention calibration (generated by analyze.py calibration)\n\n"
                                               "Balanced-accuracy threshold per collection; 5-fold CV estimate on the 40-query calibration split. "
                                               "Chance = 0.5.\n\n" + t.to_markdown(index=False) + "\n")
    print(t.to_string(index=False))


def select():
    t = pd.read_csv(R / "dev_summary.csv").set_index("config")
    lat = pd.read_csv(R / "latency_summary.csv").set_index("config")
    s = pd.read_csv(R / "dev_stats.csv")
    s = s[s.settings == "Matcher"].set_index("config")
    base_ram = t.loc[BASE, "embed_mem_mb"]
    res, md = {}, ["# exp03 — selection (pre-registered rule, PLAN.md)\n"]
    for prof, budget in BUDGET.items():
        ok = lat[lat["p95 ms"] <= budget].index
        ok = [c for c in ok if t.loc[c, "embed_mem_mb"] + t.loc[c, "rerank_mem_mb"] - base_ram <= RAM_BUDGET_MB]
        best = max(ok, key=lambda c: (t.loc[c, "Matcher MRR"], -lat.loc[c, "p95 ms"]))
        sig = best != BASE and (s.loc[best, "CI lo"] > 0 or (s.loc[best, "McNemar p"] < 0.05 and s.loc[best, "cand-only@1"] > s.loc[best, "base-only@1"]))
        chosen = best if sig else BASE
        res[prof] = {"budget_p95_ms": budget, "within_budget": ok, "best_in_budget": best, "significant_vs_baseline": bool(sig),
                     "selected": chosen}
        md += [f"## {prof} (p95 ≤ {budget} ms, extra RAM ≤ {RAM_BUDGET_MB} MB)\n",
               f"- Within budget: {', '.join(f'`{c}`' for c in ok)}",
               f"- Highest dev Matcher MRR within budget: `{best}` (MRR {t.loc[best, 'Matcher MRR']}, p95 {lat.loc[best, 'p95 ms']} ms)",
               f"- Significant vs baseline on dev: {bool(sig)}" + (f" (MRR diff {s.loc[best, 'MRR diff']}, CI [{s.loc[best, 'CI lo']}, {s.loc[best, 'CI hi']}], McNemar p {s.loc[best, 'McNemar p']})" if best != BASE else ""),
               f"- **Selected: `{chosen}`**", ""]
    json.dump(res, open(HERE / "selection.json", "w"), indent=1)
    (R / "selection.md").write_text("\n".join(md) + "\n")
    print("\n".join(md))


if __name__ == "__main__":
    {"dev": dev, "calibration": calibration, "select": select}[sys.argv[1]]()
