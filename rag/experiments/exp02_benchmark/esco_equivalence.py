"""Apply every job chunker to the 1,621 ESCO entries to show which methods would split them.
In the benchmark ESCO is always indexed one entry = one chunk; this documents why that choice loses nothing.
-> results/esco_equivalence.md"""
import sys
from pathlib import Path

import numpy as np
import pandas as pd

HERE = Path(__file__).parent
sys.path.insert(0, str(HERE.parents[1]))
import run  # noqa: E402
from chunkers import CHUNKERS  # noqa: E402
from corpus import load_esco  # noqa: E402

esco = [{"doc_id": e["doc_id"], "title": e["title"], "text": e["text"]} for e in load_esco()]
words = np.array([len(e["text"].split()) for e in esco])
rows = []
for name, f in CHUNKERS.items():
    enc = (lambda t: run.encode("e5-small", t)) if name == "semantic" else None
    n = np.array([len({(c.get("parent_start", c["start"]), c.get("parent_end", c["end"]))
                       for c in (f(e, enc) if enc else f(e))}) for e in esco])
    rows.append({"chunker": name, "entries kept whole": int((n == 1).sum()), "entries split": int((n > 1).sum()),
                 "max pieces": int(n.max()), "same boundaries as 1 entry = 1 chunk": bool((n == 1).all())})
table = pd.DataFrame(rows)
md = ("# ESCO entries under each chunker (generated by esco_equivalence.py)\n\n"
      f"1,621 entries, {words.mean():.0f} words on average (max {words.max()}). Parent-child counts returned parents. "
      "Structure-aware keeps boundaries but adds its Job/Section prefix, which is meaningless for ESCO.\n\n"
      + table.to_markdown(index=False) + "\n")
(HERE / "results/esco_equivalence.md").write_text(md)
print(md)
