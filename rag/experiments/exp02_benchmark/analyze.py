"""Summarise exp02 results and apply the pre-registered selection rule (PLAN.md).

    python analyze.py dev       # -> results/dev_summary.md, selection.json
    python analyze.py holdout   # -> results/holdout_summary.md  (never changes selection.json)
"""
import json
import sys
from math import comb
from pathlib import Path

import numpy as np
import pandas as pd

HERE = Path(__file__).parent
R = HERE / "results"
BASE = ("structure", "dense:e5-small")
MAX_MS = 300
GROUPS = {"ESCO": ["esco"], "jobs scoped": ["scoped"], "jobs global": ["global"], "Matcher (ESCO + scoped)": ["esco", "scoped"]}


def metrics(g):
    r = g["rank"]
    return {"n": len(g), "hit@1": int((r == 1).sum()), "hit@5": int((r <= 5).sum()), "hit@10": int((r <= 10).sum()),
            "MRR": round(float((1 / r).fillna(0).mean()), 3), "nDCG@10": round(float((1 / np.log2(r + 1)).fillna(0).mean()), 3)}


def mcnemar(a, b):
    x, y = int((a & ~b).sum()), int((~a & b).sum())
    n = x + y
    return x, y, (min(1.0, 2 * sum(comb(n, k) for k in range(min(x, y) + 1)) / 2 ** n) if n else 1.0)


def boot_ci(diff, n=2000, seed=0):
    rng = np.random.default_rng(seed)
    means = [diff[rng.integers(0, len(diff), len(diff))].mean() for _ in range(n)]
    return float(np.percentile(means, 2.5)), float(np.percentile(means, 97.5))


def summarise(split):
    df = pd.read_csv(R / f"{split}_per_query.csv")
    meta = pd.read_csv(R / f"{split}_configs.csv").set_index(["chunker", "retriever"])
    keys = df[["phase", "chunker", "retriever"]].drop_duplicates().values.tolist()
    ans = df[df.type != "none"]
    rows = []
    for phase, ch, rt in keys:
        g = ans[(ans.chunker == ch) & (ans.retriever == rt)]
        none = df[(df.type == "none") & (df.chunker == ch) & (df.retriever == rt)]
        row = {"phase": phase, "chunker": ch, "retriever": rt}
        for name, settings in GROUPS.items():
            m = metrics(g[g.setting.isin(settings)])
            row.update({f"{name} {k}": v for k, v in m.items() if k != "n" or name == "Matcher (ESCO + scoped)"})
        row["no-answer no_match"] = f"{int((none.returned == 0).sum())}/{len(none)}"
        row["median ms"] = round(float(g.ms.median()), 1)
        row["p95 ms"] = round(float(g.ms.quantile(0.95)), 1)
        row.update(meta.loc[(ch, rt)][["job_chunks", "coverage", "chunking_s", "indexing_s", "index_mb", "model_mem_mb"]].to_dict())
        rows.append(row)
    table = pd.DataFrame(rows)

    def paired(ch, rt, settings):
        def h(c, r):
            x = ans[(ans.chunker == c) & (ans.retriever == r) & ans.setting.isin(settings)]
            return x.set_index(["qid", "setting"])["rank"].sort_index()
        a, b = h(*BASE), h(ch, rt)
        rr = lambda s: (1 / s).fillna(0).to_numpy()
        lo, hi = boot_ci(rr(b) - rr(a))
        x, y, p = mcnemar(a == 1, b == 1)
        return {"base-only hit@1": x, "cand-only hit@1": y, "McNemar p": round(p, 3),
                "MRR diff": round(float((rr(b) - rr(a)).mean()), 3), "95% CI": f"[{lo:+.3f}, {hi:+.3f}]"}

    stats = []
    for phase, ch, rt in keys:
        if (ch, rt) == BASE:
            continue
        for label, settings in (("Matcher", ["esco", "scoped"]), ("global", ["global"])):
            stats.append({"chunker": ch, "retriever": rt, "settings": label, **paired(ch, rt, settings)})
    return table, pd.DataFrame(stats)


def select(table, stats):
    """Pre-registered rule: significant improvement on Matcher settings, median <= 300 ms, no extra service."""
    m = stats[stats.settings == "Matcher"].merge(table[["chunker", "retriever", "median ms"]], on=["chunker", "retriever"])
    ok = m[((m["McNemar p"] < 0.05) & (m["cand-only hit@1"] > m["base-only hit@1"]))
           | m["95% CI"].map(lambda s: float(s[1:].split(",")[0]) > 0)]
    ok = ok[ok["median ms"] <= MAX_MS]
    chosen = ok.sort_values("MRR diff", ascending=False).head(1)
    best = m.sort_values("MRR diff", ascending=False).head(1)  # best dev candidate, shown on holdout for transparency only
    pick = lambda d: [d.chunker.iloc[0], d.retriever.iloc[0]] if len(d) else None
    return {"rule": "PLAN.md selection rule", "baseline": list(BASE), "selected": pick(chosen) or list(BASE),
            "changed": bool(len(chosen)), "best_dev_candidate_by_MRR": pick(best),
            "qualifying_candidates": ok[["chunker", "retriever"]].values.tolist()}


def config_key(chunker, retriever):
    rr = retriever.endswith(" > rerank")
    base = retriever.removesuffix(" > rerank")
    fusion = "rrf" if base.endswith(" RRF") else None
    return [chunker, base.removesuffix(" RRF").split("+"), fusion, rr]


def main(split):
    table, stats = summarise(split)
    md = [f"# Experiment 02 — {split} results (generated by analyze.py)\n",
          "Matcher = ESCO + job-filtered queries pooled. Recall@k = Hit@k (one relevant item counted per query). "
          "Latency = median/p95 per query on the 4-core CPU, warm models.\n"]
    for phase in table.phase.unique():
        md += [f"## {phase}\n", table[table.phase == phase].drop(columns="phase").to_markdown(index=False), ""]
    md += ["## Paired comparisons against the baseline (structure + e5-small dense)\n",
           "Bootstrap 95% CI of the MRR difference (candidate − baseline), exact McNemar on Hit@1.\n",
           stats.to_markdown(index=False), ""]
    if split == "dev":
        sel = select(table, stats)
        holdout = [config_key(*sel["baseline"]), config_key(*sel["selected"])]
        if sel["best_dev_candidate_by_MRR"]:
            holdout.append(config_key(*sel["best_dev_candidate_by_MRR"]))
        sel["evaluate_on_holdout"] = [list(x) for x in {json.dumps(h): h for h in holdout}.values()]
        (HERE / "selection.json").write_text(json.dumps(sel, indent=1))
        md += ["## Selection (pre-registered rule)\n", "```json", json.dumps(sel, indent=1), "```"]
    (R / f"{split}_summary.md").write_text("\n".join(md) + "\n")
    table.to_csv(R / f"{split}_summary.csv", index=False)
    print("\n".join(md[:2]))


if __name__ == "__main__":
    main(sys.argv[1])
