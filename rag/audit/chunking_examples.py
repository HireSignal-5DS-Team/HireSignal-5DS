"""How each chunker splits one real posting (no retrieval). -> rag/audit/chunking_examples.md

Posting: usajobs-883337000 (IT Specialist, Senior Cloud AI Engineer). Probe: the GS-14 specialized-experience
requirement list ("GS-14: One year of specialized experience ... AND 4. routinely explaining ..."), which a Matcher
needs as one unit (duration + grade + 4 required duties joined by AND)."""
import sys
from pathlib import Path

import numpy as np

HERE = Path(__file__).parent
sys.path.insert(0, str(HERE.parent))
sys.path.insert(0, str(HERE.parent / "experiments/exp02_benchmark"))
from chunkers import CHUNKERS  # noqa: E402
from corpus import load_jobs  # noqa: E402

job = next(j for j in load_jobs() if j["doc_id"] == "usajobs-883337000")
body = job["text"]
s = body.index("GS-14: One year of specialized experience")
e = body.index("routinely explaining complex technical issues") + len("routinely explaining complex technical issues")
enc = None
if "--semantic" in sys.argv:
    from sentence_transformers import SentenceTransformer
    m = SentenceTransformer("intfloat/multilingual-e5-small", device="cpu")
    enc = lambda t: m.encode(["passage: " + x for x in t], normalize_embeddings=True)
rows = ["| Chunker | Chunks for this posting | Mean words | Chunks touching the GS-14 list | List kept in one chunk | Section header kept |",
        "|---|---|---|---|---|---|"]
for name, f in CHUNKERS.items():
    if name == "semantic" and enc is None:
        rows.append("| semantic | (run with --semantic) | | | | |")
        continue
    cs = f(job, enc) if name == "semantic" else f(job)
    spans = [(c.get("parent_start", c["start"]), c.get("parent_end", c["end"])) if name == "parent_child" else (c["start"], c["end"]) for c in cs]
    touching = sorted({sp for sp in spans if sp[0] < e and sp[1] > s})
    whole = any(a <= s and b >= e for a, b in spans)
    header = all(c["text"].startswith("Job:") for c in cs)
    unit = "parent sections" if name == "parent_child" else "chunks"
    n = len(set(spans)) if name == "parent_child" else len(cs)
    rows.append(f"| {name} | {n} {unit}" + (f" ({len(cs)} children)" if name == "parent_child" else "") +
                f" | {np.mean([len(c['text'].split()) for c in cs]):.0f} | {len(touching)} | {'yes' if whole else 'no'} | {'yes' if header else 'no'} |")
md = (f"# Chunking on a real posting (generated by chunking_examples.py)\n\nPosting `usajobs-883337000` ({len(body.split())} words). "
      f"Probe passage: GS-14 specialized-experience list, characters {s}–{e} ({len(body[s:e].split())} words).\n\n" + "\n".join(rows) + "\n")
(HERE / "chunking_examples.md").write_text(md)
print(md)
