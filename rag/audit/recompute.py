"""Recompute every retrieval metric from the stored per-query results of experiments 01-03 (no model is run).

    python rag/audit/recompute.py      -> rag/audit/recomputed_metrics.csv, recompute_checks.md

Metrics use the first rank at which a gold item was retrieved (the only rank stored per query), so
Hit@k = Recall@k with one relevant item counted per query; Precision@5 cannot be recomputed (N/A).
"""
from math import comb
from pathlib import Path

import numpy as np
import pandas as pd

RAG = Path(__file__).parents[1]
OUT = Path(__file__).parent
SOURCES = {  # experiment, label set, file, rank column, config columns
    "exp01-original": (RAG / "eval/results/results.csv", "first_hit_rank", ["strategy", "model", "mode"]),
    "exp01-reviewed": (RAG / "eval/results_queries_reviewed/results.csv", "first_hit_rank", ["strategy", "model", "mode"]),
    "exp02-dev": (RAG / "experiments/exp02_benchmark/results/dev_per_query.csv", "rank", ["chunker", "retriever"]),
    "exp02-holdout": (RAG / "experiments/exp02_benchmark/results/holdout_per_query.csv", "rank", ["chunker", "retriever"]),
    "exp03-dev": (RAG / "experiments/exp03_optimization/results/dev_per_query.csv", "rank", ["config"]),
}
GROUPS = {"Matcher": ["esco", "scoped"], "ESCO": ["esco"], "job-filtered": ["scoped"], "all-jobs": ["global"]}


def metrics(r):
    r = r.astype(float)
    return {"n": len(r), **{f"Hit@{k}": int((r <= k).sum()) for k in (1, 3, 5, 10)},
            "MRR@10": round(float((1 / r).fillna(0).mean()), 3), "nDCG@10": round(float((1 / np.log2(r + 1)).fillna(0).mean()), 3)}


def mcnemar(a, b):
    x, y = int((a & ~b).sum()), int((~a & b).sum())
    n = x + y
    return min(1.0, 2 * sum(comb(n, k) for k in range(min(x, y) + 1)) / 2 ** n) if n else 1.0


def boot(d, seed, n=2000):
    rng = np.random.default_rng(seed)
    s = [d[rng.integers(0, len(d), len(d))].mean() for _ in range(n)]
    return np.percentile(s, 2.5), np.percentile(s, 97.5)


def main():
    rows = []
    for exp, (path, rank, keys) in SOURCES.items():
        df = pd.read_csv(path)
        df = df[df.type != "none"].rename(columns={rank: "r"})
        df["config"] = df[keys].astype(str).agg(" | ".join, axis=1)
        for cfg, g in df.groupby("config", sort=False):
            for grp, st in GROUPS.items():
                h = g[g.setting.isin(st)]
                if len(h):
                    rows.append({"experiment": exp, "config": cfg, "group": grp, **metrics(h["r"])})
            for lang in ("en", "fr"):
                h = g[g.setting.isin(GROUPS["Matcher"]) & (g.lang == lang)]
                if len(h):
                    rows.append({"experiment": exp, "config": cfg, "group": f"Matcher-{lang}", **metrics(h["r"])})
    t = pd.DataFrame(rows)
    t.to_csv(OUT / "recomputed_metrics.csv", index=False)

    checks = ["# Recomputation checks (generated by recompute.py)\n"]
    # 1) exp03 reported Matcher MRR vs recomputed
    rep = pd.read_csv(RAG / "experiments/exp03_optimization/results/dev_summary.csv").set_index("config")["Matcher MRR"]
    mine = t[(t.experiment == "exp03-dev") & (t.group == "Matcher")].set_index("config")["MRR@10"]
    diff = (rep - mine).abs()
    checks += [f"- exp03: {len(mine)} configurations; max |reported − recomputed| Matcher MRR = {diff.max():.4f}"]
    rep2 = pd.read_csv(RAG / "experiments/exp02_benchmark/results/dev_summary.csv")
    rep2["config"] = rep2.chunker + " | " + rep2.retriever
    mine2 = t[(t.experiment == "exp02-dev") & (t.group == "Matcher")].set_index("config")["MRR@10"]
    d2 = (rep2.set_index("config")["Matcher (ESCO + scoped) MRR"] - mine2).abs()
    checks += [f"- exp02: {len(mine2)} configurations; max |reported − recomputed| Matcher MRR = {d2.max():.4f}"]
    # 2) bootstrap seed stability + Holm correction over exp03 paired tests
    df = pd.read_csv(SOURCES["exp03-dev"][0])
    df = df[(df.type != "none") & df.setting.isin(["esco", "scoped"])]
    base = df[df.config == "structure@300 | e5-small"].set_index(["qid", "setting"])["rank"].sort_index()
    rr = lambda s: (1 / s).fillna(0).to_numpy()
    stats = []
    for cfg, g in df.groupby("config"):
        if cfg == "structure@300 | e5-small":
            continue
        c = g.set_index(["qid", "setting"])["rank"].sort_index()
        d = rr(c) - rr(base)
        lo0, hi0 = boot(d, 0)
        lo1, hi1 = boot(d, 1)
        stats.append({"config": cfg, "MRR diff": round(d.mean(), 3), "CI seed0": f"[{lo0:+.3f}, {hi0:+.3f}]",
                      "CI seed1": f"[{lo1:+.3f}, {hi1:+.3f}]", "McNemar p": round(mcnemar(base == 1, c == 1), 3)})
    s = pd.DataFrame(stats).sort_values("McNemar p")
    m = len(s)
    s["Holm-adjusted p"] = [round(min(1.0, max((m - i) * p for i, p in enumerate(s["McNemar p"].iloc[: j + 1]))), 3)
                            for j in range(m)]
    s.to_csv(OUT / "exp03_stats_recomputed.csv", index=False)
    checks += [f"- exp03 paired tests: {m} comparisons vs baseline; smallest McNemar p = {s['McNemar p'].min()}, "
               f"smallest Holm-adjusted p = {s['Holm-adjusted p'].min()}; CIs excluding 0 (seed 0): "
               f"{sum(float(x[1:].split(',')[0]) > 0 for x in s['CI seed0'])}, (seed 1): "
               f"{sum(float(x[1:].split(',')[0]) > 0 for x in s['CI seed1'])}"]
    (OUT / "recompute_checks.md").write_text("\n".join(checks) + "\n\n" + s.to_markdown(index=False) + "\n")
    print("\n".join(checks))


if __name__ == "__main__":
    main()
