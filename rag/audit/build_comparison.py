"""Build the combined experiment matrix from recomputed metrics + stored latency/memory. -> EXPERIMENT_MATRIX.md

Quality: recomputed_metrics.csv (recompute.py). Latency: exp03 repeated measurement (20 queries x 5 repeats) where
available, else the experiment's single-shot per-query timings (marked). Memory: model RSS growth recorded by the run
(indicative). Values that were never measured are N/A.
"""
from pathlib import Path

import numpy as np
import pandas as pd

A = Path(__file__).parent
RAG = A.parent
t = pd.read_csv(A / "recomputed_metrics.csv")
lat3 = pd.read_csv(RAG / "experiments/exp03_optimization/results/latency_summary.csv").set_index("config")
cfg3 = pd.read_csv(RAG / "experiments/exp03_optimization/results/dev_configs.csv").set_index("config")
sum2 = pd.read_csv(RAG / "experiments/exp02_benchmark/results/dev_summary.csv")
sum2["config"] = sum2.chunker + " | " + sum2.retriever
sum2 = sum2.set_index("config")
per3 = pd.read_csv(RAG / "experiments/exp03_optimization/results/dev_per_query.csv")
raw = {"exp01-reviewed": pd.read_csv(RAG / "eval/results_queries_reviewed/results.csv")}


def row(exp, cfg):
    g = t[(t.experiment == exp) & (t.config == cfg)].set_index("group")
    if "Matcher" not in g.index:
        return None
    m = g.loc["Matcher"]
    fr = g.loc["Matcher-fr"] if "Matcher-fr" in g.index else None
    en = g.loc["Matcher-en"] if "Matcher-en" in g.index else None
    p95, mem = "N/A", "N/A"
    if exp == "exp03-dev":
        if cfg in lat3.index:
            p95 = f"{lat3.loc[cfg, 'p95 ms']:.0f} (repeated)"
        else:
            d = per3[(per3.config == cfg) & per3.setting.isin(["esco", "scoped"])].ms
            p95 = f"{np.percentile(d, 95):.0f} (single-shot)"
        mem = f"{int(cfg3.loc[cfg, 'embed_mem_mb'] + cfg3.loc[cfg, 'rerank_mem_mb'])}"
    elif exp == "exp02-dev" and cfg in sum2.index:
        p95 = f"{sum2.loc[cfg, 'p95 ms']:.0f} (single-shot)"
        mem = f"{int(sum2.loc[cfg, 'model_mem_mb'])}"
    elif exp == "exp01-reviewed":
        d = raw[exp]
        k = cfg.split(" | ")
        ms = d[(d.strategy == k[0]) & (d.model == k[1]) & (d["mode"] == k[2]) & d.setting.isin(["esco", "scoped"])].ms
        p95 = f"{np.percentile(ms, 95):.0f} (single-shot)"
    return {"Experiment": exp, "Configuration": cfg.replace(" | ", " + "), "n": int(m["n"]), "Hit@1": int(m["Hit@1"]),
            "MRR": m["MRR@10"], "Recall@5": round(m["Hit@5"] / m["n"], 3), "nDCG@10": m["nDCG@10"],
            "EN MRR": en["MRR@10"] if en is not None else "N/A", "FR MRR (n)": f"{fr['MRR@10']} ({int(fr['n'])})" if fr is not None else "N/A",
            "p95 ms": p95, "Memory MB": mem}


rows = [r for exp in ("exp01-reviewed", "exp02-dev", "exp03-dev") for cfg in t[t.experiment == exp].config.unique()
        if (r := row(exp, cfg))]
df = pd.DataFrame(rows)
df.to_csv(A / "experiment_matrix.csv", index=False)
md = ["# Combined experiment matrix (generated by build_comparison.py)\n",
      "Matcher setting = ESCO + job-filtered queries pooled (dev set). exp01 = original evaluation re-scored on the "
      "reviewed labels (n = 40); exp02/exp03 = reviewed dev set (n = 40). Recall@5 = Hit@5 / n (one relevant item "
      "counted per query). Precision@5 is not recoverable from the stored data. Memory = model RSS growth (indicative). "
      "Configurations are comparable within an experiment; across experiments the code paths differ slightly "
      "(exp01 used Qdrant + the production Retriever, exp02/03 exact numpy search).\n",
      df.to_markdown(index=False)]
(A / "EXPERIMENT_MATRIX.md").write_text("\n".join(md) + "\n")
print(df.sort_values("MRR", ascending=False).head(8).to_string(index=False))
