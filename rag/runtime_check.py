"""Measure how the RAG behaves at runtime, each phase in a fresh process (= a real application start).

    HF_HOME=<cache> CUDA_VISIBLE_DEVICES= python rag/runtime_check.py      -> docs/RUNTIME.md

cold   : empty index folder -> load e5-small, embed all 1,818 chunks, persist (first start / after corpus change)
restart: same folder in a new process -> load e5-small, reuse stored vectors (normal application start)
bm25   : no embedding model at all (the Matcher's current in-process mode)
"""
import json
import os
import platform
import subprocess
import sys
import tempfile
import time
from pathlib import Path

HERE = Path(__file__).parent


def rss_mb():
    return int(next(l for l in open("/proc/self/status") if l.startswith("VmRSS")).split()[1]) / 1024


def child(phase, store):
    import numpy as np

    t0 = time.perf_counter()
    sys.path.insert(0, str(HERE))
    from corpus import build_chunks, load_jobs
    from evaluate import load_queries
    from retrieval import Retriever

    base_rss = rss_mb()
    chunks = build_chunks("structure")
    t1 = time.perf_counter()
    r = Retriever(chunks, model=None if phase == "bm25" else "e5-small", store_path=None if phase == "bm25" else store)
    t_init = time.perf_counter() - t1
    qs = [q for q in load_queries(load_jobs(), HERE / "eval/queries_reviewed.jsonl") if q["type"] != "none"][:20]
    mode = "bm25" if phase == "bm25" else "dense"
    filt = lambda q: {"doc_id": q["job_id"]} if q["type"] == "job" else {"source_type": "esco"}
    r.search(qs[0]["query"], mode=mode, filters=filt(qs[0]))  # warm-up
    total = []
    for _ in range(3):
        for q in qs:
            t = time.perf_counter()
            r.search(q["query"], mode=mode, filters=filt(q))
            total.append((time.perf_counter() - t) * 1000)
    out = {"phase": phase, "startup_s": round(time.perf_counter() - t0, 1), "retriever_init_s": round(t_init, 1),
           "index_reused": getattr(r, "index_reused", None), "rss_mb": round(rss_mb()), "rss_after_imports_mb": round(base_rss),
           "query_median_ms": round(float(np.median(total)), 1), "query_p95_ms": round(float(np.percentile(total, 95)), 1),
           "queries": len(total)}
    r.close()
    print(json.dumps(out))


def main():
    store = Path(tempfile.mkdtemp(prefix="rag-index-"))
    rows = []
    for phase in ("cold", "restart", "restart", "bm25"):
        res = subprocess.run([sys.executable, __file__, "--child", phase, str(store)], capture_output=True, text=True,
                             env={**os.environ, "TOKENIZERS_PARALLELISM": "false"})
        rows.append(json.loads(res.stdout.strip().splitlines()[-1]))
        print(rows[-1], flush=True)
    size = sum(f.stat().st_size for f in store.rglob("*") if f.is_file()) / 2**20
    cpu = next((l.split(":", 1)[1].strip() for l in open("/proc/cpuinfo") if l.startswith("model name")), "?")
    import torch
    env = (f"CPU: {cpu}, {os.cpu_count()} logical cores; RAM: "
           f"{int(next(l for l in open('/proc/meminfo') if l.startswith('MemTotal')).split()[1]) // 2**20} GB; "
           f"GPU: {'yes' if torch.cuda.is_available() else 'none'}; Python {platform.python_version()}, torch {torch.__version__}")
    head = "| Phase | Process startup s | Retriever init s | Index reused | RSS MB | Query median / p95 ms (embedding + search) |"
    lines = [head, "|---|---|---|---|---|---|"] + [
        f"| {r['phase']} | {r['startup_s']} | {r['retriever_init_s']} | {r['index_reused']} | {r['rss_mb']} | "
        f"{r['query_median_ms']} / {r['query_p95_ms']} |" for r in rows]
    md = (f"# Runtime measurements (generated by runtime_check.py, {time.strftime('%Y-%m-%d')})\n\nEnvironment: {env}. "
          f"Each phase is a separate process (a real application start). Index on disk: {size:.1f} MB for 1,818 vectors "
          f"(384-d, plus Qdrant metadata).\n\n" + "\n".join(lines) + "\n")
    (HERE / "docs/RUNTIME.md").write_text(md)
    print(md)


if __name__ == "__main__":
    if len(sys.argv) > 1 and sys.argv[1] == "--child":
        child(sys.argv[2], sys.argv[3])
    else:
        main()
