"""S7 Judge experiment: calibrate on train-dev, evaluate on val with REAL LoRA Matcher outputs (no Matcher call).

Protocol (fixed before any val number was looked at; docs/JUDGE.md §4):
1. Calibration items: `benchmark/results/lexical-rag-train` (lexical baseline outputs on TRAIN), train-dev cases only
   (case index % 5 == 0), re-validated by the current validator. The only Matcher predictions on train in the repo.
2. Per model: hypothesis template chosen by train-dev AUROC of the wrongness score (ties -> v1);
   then tau_fail = argmax train-dev strict-FAIL F1, tau_pass = argmin 5*missed + extra reviews (calibrate_two).
3. Val items: saved LIVE LoRA Matcher outputs (rag_opt/results/e2e/lora__*), raw outputs re-validated by the current
   validator with the provider of each arm (what the pipeline Judge sees). Same pairs for every Judge model.
4. Latency: per requirement, batch size 1, fp32 CPU, torch threads = 4, on the val items of one arm.
NLI scores are cached outside git (HS_JUDGE_CACHE, default /home/user/judge_runs/s7_cache). The test split is never read.

  python -m judge.experiment --model xsmall=cross-encoder/nli-deberta-v3-xsmall@a150876... \
      --model base=MoritzLaurer/DeBERTa-v3-base-mnli-fever-anli@6f5cf0a... --out benchmark/results/judge/s7
"""
import argparse
import hashlib
import json
import os
import statistics
import time
from pathlib import Path

from benchmark.judge_eval import (calibrate_one, calibrate_two, load_dir, metrics, pairs_for,
                                  verdicts)
from matcher.judge import HYPOTHESES, NLIJudge

REPO = Path(__file__).resolve().parents[1]
CAL_RUN = REPO / "benchmark/results/lexical-rag-train"
VAL_ARMS = {a: REPO / f"rag_opt/results/e2e/lora__{a}" for a in ("gated", "none", "bm25", "none-repeat")}
CACHE = Path(os.environ.get("HS_JUDGE_CACHE", "/home/user/judge_runs/s7_cache"))


def cached_probs(judge, tag, template, set_name, items):
    judge.hypothesis_template = template
    kinds, pairs = pairs_for(judge, items)
    key = hashlib.sha256(json.dumps(pairs).encode()).hexdigest()[:16]
    f = CACHE / f"{tag}__{template}__{set_name}__{key}.json"
    if f.exists():
        return [tuple(x) for x in json.loads(f.read_text())]
    kp = list(zip(kinds, judge.item_probs(pairs)))
    CACHE.mkdir(parents=True, exist_ok=True)
    f.write_text(json.dumps(kp))
    return kp


def latency(judge, items, n=None):
    kinds, pairs = pairs_for(judge, items[:n] if n else items)
    judge.item_probs([pairs[0]] if pairs[0] else [[("warm up", "warm up")]])
    ts = []
    for p in pairs:
        if not p:
            continue
        t = time.perf_counter()
        judge.item_probs([p])
        ts.append(time.perf_counter() - t)
    q = statistics.quantiles(ts, n=20)
    return {"n_items_with_nli": len(ts), "n_pairs": sum(len(p) for p in pairs), "p50_s": round(statistics.median(ts), 4),
            "p95_s": round(q[18], 4), "mean_s": round(statistics.fmean(ts), 4), "batch_size": 1, "dtype": "float32",
            "device": "cpu", "torch_threads": judge.torch.get_num_threads()}


def summary(m):
    s = m["strict"]
    return {"n_items": m["n_items"], "n_applicable": m["n_applicable"], "n_errors_applicable": m["n_errors"],
            "fail_precision": round(s["precision"], 3), "fail_recall": round(s["recall"], 3), "fail_f1": round(s["f1"], 3),
            "fail_tp_fp_fn": [s["tp"], s["fp"], s["fn"]],
            "false_positive_flag_rate": round(s["false_positive_flag_rate"], 3),
            "broad_recall": round(m["broad"]["recall"], 3),
            "wrong_met": m["false_approvals"]["wrong_met"], "false_approvals": m["false_approvals"]["judged_pass"],
            "false_approvals_unreviewed_by_validator": m["false_approvals"]["judged_pass_and_no_validator_review"],
            "false_approval_items": m["false_approvals"]["items"],
            "judge_review_rate": round(m["review_rate"]["judge_recommends_review"], 3),
            "validator_review_rate": round(m["review_rate"]["validator"], 3),
            "validator_or_judge_review_rate": round(m["review_rate"]["validator_or_judge_flag"], 3),
            "auroc": None if m["auroc_error_detection"] is None else round(m["auroc_error_detection"], 3),
            "ece": None if m["ece_correctness"] is None else round(m["ece_correctness"], 3),
            "verdicts": m["verdicts"]}


def markdown(result):
    L = ["# S7 NLI Judge experiment (generated by judge/experiment.py)", "",
         "Calibration: train-dev of `lexical-rag-train` (%d items, %d Matcher errors). Val: LIVE LoRA Matcher outputs "
         "(Qwen3-4B Q4_K_M + LoRA @0b6925b1), 202 requirements per arm, same pairs for every Judge. "
         "`replay-v2` = raw outputs re-validated by the current validator (what the pipeline Judge sees); "
         "`saved-v1` = decisions as saved by the live run (validator v1, still contains wrong METs). "
         "Scores are NLI softmax scores, not probabilities of correctness." % (
             result["calibration_set"]["n_items"], result["calibration_set"]["n_errors"]), "",
         "| Judge | revision | hyp. | tau_pass / tau_fail | set | FAIL precision | FAIL recall | TP/FP/FN | false approvals / wrong MET | Judge review rate | validator / validator+Judge review | AUROC |",
         "|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for tag, e in result["models"].items():
        c = e["calibration"]
        rows = [("train-dev", e["traindev"])] + [(k, v) for k, v in e["val"].items() if not k.startswith("none-repeat")]
        for name, m in rows:
            L.append(f"| {tag} | `{str(e['revision'])[:12]}` | {e['hypothesis']} | {c['tau_pass']} / {c['tau_fail']} | {name} | "
                     f"{m['fail_precision']:.3f} | {m['fail_recall']:.3f} | {'/'.join(map(str, m['fail_tp_fp_fn']))} | "
                     f"{m['false_approvals']} / {m['wrong_met']} | {m['judge_review_rate']:.3f} | "
                     f"{m['validator_review_rate']:.3f} / {m['validator_or_judge_review_rate']:.3f} | {m['auroc']} |")
    L += ["", "| Judge | params (M) | load s | latency p50 / p95 s per requirement (bs 1, fp32, 4 threads) | template AUROC on train-dev |",
          "|---|---|---|---|---|"]
    for tag, e in result["models"].items():
        lt = e["latency"]
        L.append(f"| {tag} | {e['params_m']} | {e['load_s']} | {lt['p50_s']} / {lt['p95_s']} | "
                 + ", ".join(f"{t}: {a:.3f}" for t, a in e["template_auroc_traindev"].items()) + " |")
    return "\n".join(L) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--model", action="append", required=True, help="tag=model_id_or_dir[@revision]")
    ap.add_argument("--out", required=True)
    ap.add_argument("--latency-arm", default="gated")
    a = ap.parse_args()
    _, cal = load_dir(CAL_RUN, replay=True, split_guard=("train",))
    val = {}
    for arm, d in VAL_ARMS.items():
        if d.exists():
            val[f"{arm}/replay-v2"] = load_dir(d, replay=True, split_guard=("val",))[1]
            val[f"{arm}/saved-v1"] = load_dir(d, replay=False, split_guard=("val",))[1]
    result = {"protocol": __doc__.split("NLI scores")[0].strip(), "calibration_set": {
        "run": "lexical-rag-train", "split": "train-dev (train case index % 5 == 0)", "n_items": len(cal),
        "n_errors": sum(r["decision"] != r["gold_decision"] for r, *_ in cal)},
        "val_sets": {arm: {"run_dir": str(VAL_ARMS[arm.split("/")[0]].relative_to(REPO)), "split": "val", "n_items": len(it),
                           "matcher": "LIVE Qwen3-4B-Instruct-2507 Q4_K_M + HireSignal LoRA @0b6925b1 (saved raw outputs)",
                           "validator": "current matcher/validate.py (replay of the raw outputs)" if arm.endswith("replay-v2")
                           else "decisions as saved by the live run (validator v1, before QA-025/026)"}
                     for arm, it in val.items()},
        "models": {}}
    for spec in a.model:
        tag, mid = spec.split("=", 1)
        mid, _, rev = mid.partition("@")
        t0 = time.perf_counter()
        judge = NLIJudge(mid, revision=rev or None, name=f"nli-judge:{tag}", num_threads=4)
        load_s = time.perf_counter() - t0
        per_t = {}
        for tmpl in HYPOTHESES:
            kp = cached_probs(judge, tag, tmpl, "traindev", cal)
            m = metrics(cal, verdicts(judge, cal, kp, 0.5))
            per_t[tmpl] = {"auroc": m["auroc_error_detection"], "kp": kp}
        tmpl = max(sorted(per_t), key=lambda t: (per_t[t]["auroc"] or 0, t == "v1"))
        judge.hypothesis_template = tmpl
        kp = per_t[tmpl]["kp"]
        cal2 = calibrate_two(judge, cal, kp)
        sens = {w: calibrate_two(judge, cal, kp, w_miss=w)["tau_pass"] for w in (2.0, 10.0)}
        tp, tf = cal2["tau_pass"], cal2["tau_fail"]
        entry = {"model_id": mid, "revision": judge.revision, "params_m": round(sum(p.numel() for p in judge.model.parameters()) / 1e6, 1),
                 "label_index": judge.idx, "load_s": round(load_s, 2),
                 "template_auroc_traindev": {t: per_t[t]["auroc"] for t in per_t}, "hypothesis": tmpl,
                 "calibration": {**cal2, "tau_pass_if_w_miss": sens},
                 "traindev": summary(metrics(cal, verdicts(judge, cal, kp, tau_pass=tp, tau_fail=tf))),
                 "legacy_single_tau": calibrate_one(judge, cal, kp)[0], "val": {}, "val_other_template": {}}
        for arm, items in val.items():
            for t in HYPOTHESES:
                vkp = cached_probs(judge, tag, t, f"val-{arm.replace('/', '-')}", items)
                judge.hypothesis_template = t
                ms = summary(metrics(items, verdicts(judge, items, vkp, tau_pass=tp, tau_fail=tf)))
                (entry["val"] if t == tmpl else entry["val_other_template"])[arm] = ms
            judge.hypothesis_template = tmpl
        entry["latency"] = latency(judge, val[f"{a.latency_arm}/replay-v2"])
        if Path(mid).is_dir() and "snapshots" not in Path(mid).parts:  # local fine-tuned dir: keep its calibration with it
            (Path(mid) / "judge_calibration.json").write_text(json.dumps(
                {"tau_pass": tp, "tau_fail": tf, "hypothesis": tmpl, "revision": judge.revision,
                 "source": "judge/experiment.py, train-dev of lexical-rag-train (train case % 5 == 0)"}, indent=2) + "\n")
        result["models"][tag] = entry
        print(json.dumps({tag: {k: entry[k] for k in ("hypothesis", "calibration", "latency")}}, default=str)[:2000], flush=True)
        del judge
    out = Path(a.out)
    out.mkdir(parents=True, exist_ok=True)
    for e in result["models"].values():
        e["calibration"].pop("strict_f1_grid_raw", None)
    (out / "experiment.json").write_text(json.dumps(result, indent=2, default=str) + "\n")
    (out / "experiment.md").write_text(markdown(result))
    print(f"wrote {out / 'experiment.json'}")


if __name__ == "__main__":
    main()
